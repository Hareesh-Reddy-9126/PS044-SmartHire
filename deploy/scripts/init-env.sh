#!/usr/bin/env bash
# Generates deploy/.env for the production stack with fresh random secrets.
#
# Usage:
#   DOMAIN=smarthire.<vm-public-ip>.sslip.io ACME_EMAIL=you@example.com \
#     ./deploy/scripts/init-env.sh
#
# Optional environment variables:
#   NOTIFICATION_SENDER_TYPE   smtp (default) or logging. `logging` records notifications without
#                              sending mail; use it only until SMTP credentials are available.
#   SMTP_HOST, SMTP_PORT, SMTP_USERNAME, SMTP_PASSWORD, SMTP_FROM
#                              Required when NOTIFICATION_SENDER_TYPE=smtp.
#   ADMIN_SIGNUP_CODE          One-time invitation code for the first administrator. Leave unset
#                              to keep admin self-registration disabled.
#   BACKUP_DIR                 Defaults to /var/backups/smarthire.
#
# The file is written with mode 600 and no secret value is ever printed to stdout or a log.
set -euo pipefail
umask 077

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_FILE="${ENV_FILE:-$REPO_ROOT/deploy/.env}"

: "${DOMAIN:?Set DOMAIN, for example smarthire.203.0.113.10.sslip.io}"
: "${ACME_EMAIL:?Set ACME_EMAIL for certificate expiry notices}"

if [[ -f "$ENV_FILE" ]]; then
  echo "ERROR: $ENV_FILE already exists; move it aside before regenerating." >&2
  exit 1
fi

SENDER_TYPE="${NOTIFICATION_SENDER_TYPE:-smtp}"
case "$SENDER_TYPE" in
  smtp)
    : "${SMTP_HOST:?SMTP_HOST is required for smtp (set NOTIFICATION_SENDER_TYPE=logging to skip mail)}"
    : "${SMTP_FROM:?SMTP_FROM is required for smtp}"
    ;;
  logging) ;;
  *)
    echo "ERROR: NOTIFICATION_SENDER_TYPE must be 'smtp' or 'logging'." >&2
    exit 1
    ;;
esac

# 40+ alphanumeric characters: safe in a JDBC URL, a shell heredoc and a YAML value.
rand() {
  local raw
  raw="$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9')"
  printf '%s' "${raw:0:${1:-40}}"
}

DB_PASSWORD="$(rand 40)"
# PKCS#8 RSA private key, flattened to the single-line base64 body that JwtKeyConfig expects.
JWT_KEY="$(openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 2>/dev/null \
  | sed '1d;$d' | tr -d '\n')"

cat > "$ENV_FILE" <<EOF
# Generated by deploy/scripts/init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Contains live secrets: never commit, copy to a chat, or include in a report.

# ---- Public deployment ----
DOMAIN=${DOMAIN}
ACME_EMAIL=${ACME_EMAIL}
GATEWAY_CORS_ALLOWED_ORIGINS=https://${DOMAIN}

# ---- PostgreSQL ----
POSTGRES_DB=smarthire
POSTGRES_USER=smarthire
POSTGRES_PASSWORD=${DB_PASSWORD}

# ---- Auth service ----
AUTH_JWT_PRIVATE_KEY=${JWT_KEY}
AUTH_JWT_ISSUER=https://${DOMAIN}/auth
AUTH_JWT_AUDIENCE=smarthire
AUTH_ADMIN_SIGNUP_CODE=${ADMIN_SIGNUP_CODE:-}

# ---- Notifications ----
NOTIFICATION_SENDER_TYPE=${SENDER_TYPE}
NOTIFICATION_SMTP_HOST=${SMTP_HOST:-}
NOTIFICATION_SMTP_PORT=${SMTP_PORT:-587}
NOTIFICATION_SMTP_USERNAME=${SMTP_USERNAME:-}
NOTIFICATION_SMTP_PASSWORD=${SMTP_PASSWORD:-}
NOTIFICATION_SMTP_FROM=${SMTP_FROM:-}
NOTIFICATION_DELIVERY_MAX_ATTEMPTS=3
NOTIFICATION_DELIVERY_RETRY_BACKOFF_MS=500

# ---- AI service (mock is the only provider implemented in this build) ----
AI_ENABLED=true
AI_PROVIDER=mock
AI_CLAUDE_API_KEY=
AI_CLAUDE_MODEL=

# ---- Backups ----
BACKUP_DIR=${BACKUP_DIR:-/var/backups/smarthire}
BACKUP_RETENTION_DAYS=7
DOCUMENTS_VOLUME=smarthire_document-data
EOF

chmod 600 "$ENV_FILE"
echo "Wrote $ENV_FILE (mode 600, secrets not printed)."

# The systemd backup units read this file rather than deploy/.env (which is only for compose).
BACKUP_ENV="/etc/smarthire/backup.env"
if [[ ${EUID} -eq 0 && "$(uname -s)" == "Linux" ]]; then
  install -d -m 755 /etc/smarthire
  cat > "$BACKUP_ENV" <<EOF
BACKUP_DIR=${BACKUP_DIR:-/var/backups/smarthire}
BACKUP_RETENTION_DAYS=7
EOF
  chmod 644 "$BACKUP_ENV"
  echo "Wrote $BACKUP_ENV for the systemd backup timer."
else
  echo "Skipped $BACKUP_ENV (run as root to write it, or create it from the runbook)."
fi
